// Paragraphe : accepte une chaîne ou un tableau de runs {t, b}
function p(content, opts) {
  const o = opts || {};
  const runs = (Array.isArray(content) ? content : [{ t: content }]).map(r =>
    new TextRun({ text: r.t, bold: !!r.b, italics: !!r.i, size: 24, color: "000000", font: FONT_BODY }));
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: 312, after: o.after !== undefined ? o.after : 120 },
    children: runs,
  });
}
function caption(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER, spacing: { line: 312, before: 80, after: 160 },
    children: [new TextRun({ text, size: 21, color: "606060", font: FONT_BODY })],
  });
}
function tableTitle(text) {
  return new Paragraph({
    keepNext: true, spacing: { line: 312, before: 160, after: 80 },
    children: [new TextRun({ text, bold: true, size: 21, color: P.headingColor, font: FONT_BODY })],
  });
}
// Tableau horizontal-only conforme (pourcentages, margins, header répété)
function dataTable(headers, rows, widths) {
  const mk = (text, isHeader, w) => new TableCell({
    width: { size: w, type: WidthType.PERCENTAGE },
    shading: isHeader ? { type: ShadingType.CLEAR, fill: P.table.headerBg } : undefined,
    margins: { top: 60, bottom: 60, left: 120, right: 120 },
    children: [new Paragraph({
      spacing: { line: 312 },
      children: [new TextRun({ text: safeText(text, "—"), bold: isHeader, size: 21, color: isHeader ? P.table.headerText : "000000", font: FONT_BODY })],
    })],
  });
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 2, color: P.table.headerBg },
      bottom: { style: BorderStyle.SINGLE, size: 2, color: P.table.headerBg },
      left: NB, right: NB,
      insideHorizontal: { style: BorderStyle.SINGLE, size: 1, color: P.table.innerLine },
      insideVertical: NB,
    },
    rows: [
      new TableRow({ tableHeader: true, cantSplit: true, children: headers.map((t, i) => mk(t, true, widths[i])) }),
      ...rows.map(r => new TableRow({ cantSplit: true, children: r.map((t, i) => mk(t, false, widths[i])) })),
    ],
  });
}
